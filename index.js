const intakeQuestions = [
  "يرجى توضيح موضوع المشكلة باختصار.",
  "ما تاريخ الواقعة أو بداية المشكلة تقريبًا؟",
  "هل سبق اتخاذ إجراء قانوني أو تحرير محضر أو رفع دعوى؟ يرجى التوضيح.",
  "هل توجد جلسة أو موعد قانوني قريب؟ يرجى ذكر التاريخ إن وجد.",
  "هل توجد مستندات أو عقود أو مراسلات متعلقة بالموضوع؟"
];

function docsText(docs) {
  return docs.map((d, i) => `${i + 1}- ${d}`).join("\n");
}

function beginIntake(state, sectionNumber, serviceNumber) {
  const section = services[sectionNumber];
  const item = section.options[serviceNumber];

  state.stage = "intake";
  state.section = sectionNumber;
  state.service = serviceNumber;
  state.answers = [];
  state.questionIndex = 0;

  return `تم اختيار:

القسم: ${section.title}
الخدمة: ${item.title}

المستندات المقترح تجهيزها:

${docsText(item.docs)}

هذه قائمة تجهيز أولية وليست قائمة رسمية نهائية أو إلزامية، وقد تختلف بحسب الوقائع.

${intakeQuestions[0]}`;
}

function finishIntake(state) {
  const section = services[state.section];
  const item = section.options[state.service];

  return `تم تسجيل البيانات الأولية:

القسم: ${section.title}
الخدمة: ${item.title}

الإجابات:
${state.answers.map((a, i) => `${i + 1}- ${a}`).join("\n")}

المستندات المقترح تجهيزها:
${docsText(item.docs)}

يرجى تجهيز الأوراق المتاحة والتواصل مع المكتب لتحديد موعد.

هذه البيانات لا تمثل رأيًا قانونيًا نهائيًا، ولا تغني عن مراجعة المحامي للمستندات والوقائع.

1- حجز استشارة
0- القائمة الرئيسية`;
}

// ============================================================
