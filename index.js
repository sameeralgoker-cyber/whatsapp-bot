// ============================================================

function reply(message, state = {}, name = "") {
  const text = String(message || "").trim();

  if (!state.stage) resetState(state);

  if (
    ["مرحبا", "مرحبًا", "السلام عليكم", "أهلا", "أهلًا", "ابدأ"]
      .includes(text)
  ) {
    resetState(state);
    return welcome(name);
  }

  if (text === "0") {
    resetState(state);
    return welcome(name);
  }

  if (state.stage === "main") {
    if (services[text]) {
      state.section = text;
      state.stage = "services";
      return showServices(text);
    }

    if (text === "9") {
      state.stage = "booking";
      return `طلب حجز استشارة.

يرجى إرسال:
1- الاسم.
2- رقم الهاتف.
3- موضوع الاستشارة.
4- الوقت المناسب.

سيقوم المكتب بمراجعة الطلب والتواصل لتأكيد الموعد.

اكتب 0 للعودة.`;
    }

    if (text === "10") {
      state.stage = "followup";
      return `لمتابعة ملف قائم يرجى إرسال:

1- اسم صاحب الملف.
2- رقم الملف إن وجد.
3- رقم القضية إن وجد.
4- آخر إجراء أو جلسة إن أمكن.

يرجى عدم إرسال بيانات شديدة الحساسية عبر المحادثة.

اكتب 0 للعودة.`;
    }

    return welcome(name);
  }

  if (state.stage === "services") {
    const section = services[state.section];

    if (!section || !section.options[text]) {
      return showServices(state.section);
    }

    return beginIntake(state, state.section, text);
  }

  if (state.stage === "intake") {
    state.answers.push(text);
    state.questionIndex++;

    if (state.questionIndex < intakeQuestions.length) {
      return intakeQuestions[state.questionIndex];
    }

    state.stage = "complete";
    return finishIntake(state);
  }

  if (state.stage === "booking") {
    state.bookingDetails = text;
    state.stage = "booking_complete";

    return `تم استلام طلب الحجز بصورة مبدئية.

${text}

سيقوم المكتب بمراجعة الطلب والتواصل لتأكيد الموعد.

اكتب 0 للعودة للقائمة الرئيسية.`;
  }

  if (state.stage === "followup") {
    state.followupDetails = text;
    state.stage = "followup_complete";

    return `تم استلام بيانات متابعة الملف بصورة مبدئية.

${text}

سيقوم المكتب بمراجعة البيانات والتواصل عند الحاجة.

اكتب 0 للعودة للقائمة الرئيسية.`;
  }

  if (state.stage === "complete") {
    if (text === "1") {
      state.stage = "booking";
      return `طلب حجز استشارة.

يرجى إرسال الاسم ورقم الهاتف وموضوع الاستشارة والوقت المناسب.

اكتب 0 للعودة.`;
    }

    resetState(state);
    return welcome(name);
  }

  if (
    state.stage === "booking_complete" ||
    state.stage === "followup_complete"
  ) {
    resetState(state);
    return welcome(name);
  }

  resetState(state);
  return welcome(name);
}

