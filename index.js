// chatbot - law office

function getWelcome(name = "") {
  return `مرحبًا ${name ? "أستاذ " + name : "بكم"}،
نشكركم على التواصل مع المكتب القانوني.

يرجى اختيار الخدمة المطلوبة وكتابة رقمها:

1- إرسال تفاصيل مسألة قانونية جديدة
2- حجز موعد مع المحامي
3- الاستفسار عن تكلفة الاستشارة
4- متابعة قضية أو ملف قائم
5- التحدث مع موظف أو المحامي
6- معرفة المستندات المطلوبة`;
}

function reply(message, name = "") {
  const text = message.trim();

  if (text === "السلام عليكم" || text === "مرحبا" || text === "أهلا") {
    return getWelcome(name);
  }

  if (text === "6") {
    return `يرجى تحديد نوع المسألة القانونية لمعرفة المستندات المطلوبة:

1- مسائل الأحوال الشخصية
2- المسائل المدنية
3- المسائل الجنائية
4- المسائل التجارية
5- مسائل العمل
6- مسائل العقارات
7- مسائل مجلس الدولة والقضاء الإداري
8- مسائل أخرى

يرجى كتابة رقم الاختيار.`;
  }

  if (text === "1") {
    return "يرجى توضيح المسألة القانونية بشكل مختصر، دون إرسال بيانات أو مستندات حساسة.";
  }

  if (text === "2") {
    return "لحجز موعد، يرجى إرسال الاسم وبيان الموعد المناسب، وسيتم مراجعة طلبكم.";
  }

  if (text === "3") {
    return "تختلف تكلفة الاستشارة بحسب طبيعة المسألة القانونية. يرجى توضيح موضوع الاستشارة بشكل مختصر.";
  }

  if (text === "4") {
    return "لمتابعة قضية أو ملف قائم، يرجى إرسال رقم الملف أو بيان مختصر يساعد المكتب على تحديد الملف.";
  }

  if (text === "5") {
    return "سيتم تسجيل طلبكم للتواصل مع موظف المكتب. يرجى كتابة الاسم وموضوع التواصل.";
  }

  if (text === "8") {
    return "يرجى توضيح نوع المسألة القانونية بشكل عام.";
  }

  return "لم أفهم الاختيار. يرجى كتابة رقم الخدمة المطلوبة من القائمة، أو كتابة مرحبا لعرض القائمة.";
}

// اختبار مبدئي
console.log(reply("السلام عليكم"));
console.log(reply("6"));
console.log(reply("1"));
